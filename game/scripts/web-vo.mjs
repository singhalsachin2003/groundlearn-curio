// Web build only: the app keeps its voice clips inside the code (it has no file server),
// but on the web that makes the first download 3 MB heavier. This splits src/vo.ts into one
// small .mp3 per line (fetched only when a line is spoken) and a map of line → file.
import { readFileSync, writeFileSync, mkdirSync, rmSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const src = readFileSync(resolve(here, '../src/vo.ts'), 'utf8');
const VO = JSON.parse(src.slice(src.indexOf('{', src.indexOf('=')), src.lastIndexOf('}') + 1));

const outDir = resolve(here, '../public-web/vo');
rmSync(outDir, { recursive: true, force: true });
mkdirSync(outDir, { recursive: true });

const map = {};
let bytes = 0;
for (const [key, dataUrl] of Object.entries(VO)) {
  const buf = Buffer.from(dataUrl.slice(dataUrl.indexOf(',') + 1), 'base64');
  const name = createHash('sha1').update(buf).digest('hex').slice(0, 12) + '.mp3';
  writeFileSync(resolve(outDir, name), buf);
  map[key] = name;
  bytes += buf.length;
}

writeFileSync(resolve(here, '../src/vo.web.gen.ts'),
  '// Generated by game/scripts/web-vo.mjs for the web build. Do not edit.\n' +
  '// Same shape as vo.ts, but each value is the address of a small .mp3 next to the page.\n' +
  `const FILES: Record<string, string> = ${JSON.stringify(map)};\n` +
  "const base = new URL('vo/', document.baseURI).href;\n" +
  'export const VO: Record<string, string> = Object.fromEntries(Object.entries(FILES).map(([k, f]) => [k, base + f]));\n');

console.log(`web voices: ${Object.keys(map).length} clips, ${(bytes / 1024).toFixed(0)} KB → public-web/vo/`);
