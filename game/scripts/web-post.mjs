// Web build only, after `vite build --mode web`: write the offline cache (sw.js).
// It stores the island, three.js and every lab world on the first visit, so the next visit
// opens instantly and works without internet. Voice clips are cached as they are played.
import { readdirSync, statSync, writeFileSync, readFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { dirname, resolve, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const dist = resolve(here, '../dist-web');

const files = [];
(function walk(dir) {
  for (const name of readdirSync(dir)) {
    const p = resolve(dir, name);
    if (statSync(p).isDirectory()) walk(p);
    else files.push(relative(dist, p).replace(/\\/g, '/'));
  }
})(dist);

const core = files.filter(f => !f.startsWith('vo/') && f !== 'sw.js' && f !== 'index.html');
const hash = createHash('sha1');
for (const f of [...core, 'index.html']) hash.update(f).update(readFileSync(resolve(dist, f)));
const version = hash.digest('hex').slice(0, 10);

const sw = `// Generated by game/scripts/web-post.mjs. Offline cache for Curio Island on the web.
const CACHE = 'curio-${version}';
const CORE = ${JSON.stringify(['./', ...core])};
self.addEventListener('install', e => {
  e.waitUntil(caches.open(CACHE).then(c => c.addAll(CORE)).then(() => self.skipWaiting()));
});
self.addEventListener('activate', e => {
  e.waitUntil(caches.keys().then(keys => Promise.all(keys.filter(k => k.startsWith('curio-') && k !== CACHE).map(k => caches.delete(k)))).then(() => self.clients.claim()));
});
self.addEventListener('fetch', e => {
  const req = e.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== location.origin) return;
  // The page itself: try the network first so updates arrive, fall back to the cache offline.
  if (req.mode === 'navigate') {
    e.respondWith(fetch(req).then(r => { const copy = r.clone(); caches.open(CACHE).then(c => c.put('./', copy)); return r; }).catch(() => caches.match('./')));
    return;
  }
  // Everything else has a content hash in its name (or never changes): cache first.
  e.respondWith(caches.match(req).then(hit => hit || fetch(req).then(r => {
    if (r.ok) { const copy = r.clone(); caches.open(CACHE).then(c => c.put(req, copy)); }
    return r;
  })));
});
`;
writeFileSync(resolve(dist, 'sw.js'), sw);

const size = f => statSync(resolve(dist, f)).size;
const kb = n => (n / 1024).toFixed(0) + ' KB';
const voices = files.filter(f => f.startsWith('vo/'));
console.log(`web build → game/dist-web (cache ${version})`);
console.log(`  page and island code: ${kb(core.concat('index.html').filter(f => !/worlds|colour|inventor|tinkerer|explorer/.test(f)).reduce((a, f) => a + size(f), 0))}`);
console.log(`  everything except voices: ${kb(core.concat('index.html').reduce((a, f) => a + size(f), 0))}`);
console.log(`  ${voices.length} voice clips: ${kb(voices.reduce((a, f) => a + size(f), 0))} (loaded one at a time when spoken)`);
