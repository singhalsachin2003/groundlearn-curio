// Make the single-file build safe to embed, then hand it to the Expo app as a string.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const distFile = resolve(here, '../dist/index.html');
let html = readFileSync(distFile, 'utf8');

// The bundle holds whole HTML pages as strings. Inside an inline <script>, a literal
// "</script" or "<!--" would end or confuse the script, so escape them in the bundle.
const open = html.indexOf('<script type="module"');
if (open < 0) throw new Error('no module script in build');
const bodyStart = html.indexOf('>', open) + 1;
const close = html.lastIndexOf('</script>');
const js = html.slice(bodyStart, close).replace(/<\/script/gi, '<\\/script').replace(/<!--/g, '<\\!--');
html = html.slice(0, bodyStart) + js + html.slice(close);
writeFileSync(distFile, html);

const out = resolve(here, '../../app/src/game/gameHtml.ts');
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, '// Generated by game/scripts/export-to-app.mjs. Do not edit.\nexport default ' + JSON.stringify(html) + ';\n');
console.log(`game build: ${(html.length / 1024).toFixed(0)} KB → app/src/game/gameHtml.ts`);
